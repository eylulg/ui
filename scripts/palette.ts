/**
 * Colour scale generation for the theme variants. Dev only: uses culori.
 *
 * Every brand scale uses the same oklch lightness per step, so a given step has
 * (almost exactly) the same luminance and therefore the same contrast in
 * every variant. Chroma follows a fixed profile that peaks at step 500 and is
 * reduced per step until the colour fits in sRGB, keeping hue and lightness.
 */
import { clampChroma, converter, formatCss, parse, type Oklch } from 'culori';
import {
  scaleSteps,
  type ColorScale,
  type ScaleStep,
  type VariantColors,
  type VariantName,
  type VariantSpec,
} from '../src/styles/themes/variants';

/** oklch L for brand scales. */
export const brandLightness: Record<ScaleStep, number> = {
  '25': 0.985,
  '50': 0.97,
  '100': 0.935,
  '200': 0.885,
  '300': 0.81,
  '400': 0.715,
  '500': 0.625,
  '600': 0.535,
  '700': 0.47,
  '800': 0.395,
  '900': 0.325,
  '950': 0.255,
};

export const chromaProfile: Record<ScaleStep, number> = {
  '25': 0.08,
  '50': 0.16,
  '100': 0.32,
  '200': 0.52,
  '300': 0.76,
  '400': 0.94,
  '500': 1,
  '600': 0.96,
  '700': 0.86,
  '800': 0.72,
  '900': 0.58,
  '950': 0.44,
};

const round = (value: number, digits: number) => Number(value.toFixed(digits));

function step(l: number, c: number, h: number): string {
  const color: Oklch = { mode: 'oklch', l, c, h };
  const fitted = clampChroma(color, 'oklch', 'rgb') as Oklch;
  const chroma = round(fitted.c ?? 0, 4);
  return formatCss({ mode: 'oklch', l: round(l, 3), c: chroma, h: chroma === 0 ? 0 : h }) ?? '';
}

export function buildScale(
  lightness: Record<ScaleStep, number>,
  hue: number,
  chroma: number,
): ColorScale {
  return Object.fromEntries(
    scaleSteps.map((s) => [s, step(lightness[s], chroma * chromaProfile[s], hue)]),
  ) as ColorScale;
}

const toOklch = converter('oklch');

/** The brand scale takes the hue and chroma of the light seed, so tints and text match it. */
export function buildVariantScales(spec: VariantSpec): VariantColors {
  const seed = parse(spec.seed.light);
  if (!seed) throw new Error(`Cannot parse seed "${spec.seed.light}" of ${spec.name}`);
  const { c = 0, h = 0 } = toOklch(seed);
  return { brand: buildScale(brandLightness, round(h, 1), round(c, 4)) };
}

export function buildAllScales(specs: Record<VariantName, VariantSpec>) {
  return Object.fromEntries(
    Object.entries(specs).map(([name, spec]) => [name, buildVariantScales(spec)]),
  ) as Record<VariantName, VariantColors>;
}

export function scalesModule(specs: Record<VariantName, VariantSpec>): string {
  const data = JSON.stringify(buildAllScales(specs), null, 2);
  return [
    '/* Generated by `npm run themes` (scripts/generate-themes.ts). Do not edit by hand. */',
    "import type { VariantColors, VariantName } from './variants';",
    '',
    `export const scales: Record<VariantName, VariantColors> = ${data};`,
    '',
  ].join('\n');
}
